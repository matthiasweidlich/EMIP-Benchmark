#!/usr/bin/env bash
# Build the EMIP silver layer into a DuckDB database.
# Usage: silver/build.sh [output.duckdb]   (default: silver/emip.duckdb)
# Requires python3 with the duckdb package (pip install duckdb).
set -euo pipefail
cd "$(dirname "$0")/.."

DB=${1:-silver/emip.duckdb}

# GDELT full files are committed zipped; extracted copies are gitignored.
for z in gkg_energy_enriched gkg_energy_event_link; do
    if [ ! -f "data/04-gdelt-news-events/$z.csv" ]; then
        echo "== unzipping $z.zip"
        unzip -q -o "data/04-gdelt-news-events/$z.zip" -d data/04-gdelt-news-events
    fi
done

rm -f "$DB"
python3 - "$DB" <<'EOF'
import glob, os, sys
import duckdb

FULL_WEATHER = ("data/06-weather/"
                "sensor_community_weather_western_europe_2021-11-08_2021-11-14_sorted.csv")

con = duckdb.connect(sys.argv[1])
for path in sorted(glob.glob("silver/sql/*.sql")):
    print(f"== {path}", flush=True)
    con.execute(open(path).read())
    # Prefer the full-week weather file (regenerated by the dataset scripts,
    # gitignored) over the committed 100 MB sample.
    if path.endswith("00_bronze_views.sql") and os.path.exists(FULL_WEATHER):
        print(f"== using full weather file {FULL_WEATHER}", flush=True)
        con.execute(f"""CREATE OR REPLACE VIEW bronze.weather AS
            SELECT * FROM read_csv('{FULL_WEATHER}', header=true, sample_size=-1)""")
    # Include any locally downloaded full weekday tick files (gitignored,
    # ~5 GB each) next to the committed weekend files. The day-08 sample100
    # is dropped when the full day-08 file is present (it is a subset).
    if path.endswith("00_bronze_views.sql"):
        tick_dir = "data/01-debs-tick-stream"
        weekday = sorted(p for d in ("08", "09", "10", "11", "12")
                         for p in glob.glob(f"{tick_dir}/debs2022-gc-trading-day-{d}-11-21.csv"))
        if weekday:
            files = [f"{tick_dir}/debs2022-gc-trading-day-13-11-21.csv",
                     f"{tick_dir}/debs2022-gc-trading-day-14-11-21.csv"] + weekday
            if not any(p.endswith("day-08-11-21.csv") for p in weekday):
                files.append(f"{tick_dir}/debs2022-gc-trading-day-08-11-21_sample100.csv")
            print(f"== tick files: {', '.join(os.path.basename(f) for f in files)}", flush=True)
            union = "\nUNION ALL\n".join(
                f"SELECT *, '{os.path.basename(f)}' AS filename FROM bronze_read_ticks('{f}')"
                for f in files)
            con.execute(f"CREATE OR REPLACE VIEW bronze.market_tick AS\n{union}")
print("== row counts")
print(con.sql("""
    SELECT table_name, estimated_size AS rows
    FROM duckdb_tables() WHERE schema_name = 'silver'
    ORDER BY table_name"""))
EOF
echo "== silver layer built: $DB"
